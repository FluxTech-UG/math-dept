"""Ledger invariants I1 to I21.

Run: `python -m mdept.check [--root PATH] [--run-counterexamples] [--family] [--lean]`

Every invariant raises `CheckError` on the first violation it finds, naming the
invariant, the offending path, and the offending field. There is no warnings
tier and no partial pass: I9b is the single informational check, and it is
reported as a notice that also lands in `ledger/INDEX.md` section 7.

Modes:

- plain, the default: everything that needs only this repo's markdown.
- `--run-counterexamples`: additionally executes each counterexample artifact
  and requires its witness to verify.
- `--family`: additionally resolves sibling repos through `repos.yaml`. A repo
  listed there and absent from disk fails; it never skips.
- `--lean`: additionally reads `audit/latest.json` and checks formal pointers,
  axioms, and statement hashes against it. A stale audit fails.

Two scoping decisions worth knowing before reading the code:

- I12 scans the surfaces that make claims about entries (the ledger, proofs,
  counterexample notes, the bibliography, and on the private side triage,
  inbox and sources). It does not scan instructional prose (`docs/`, `README.md`,
  `CLAUDE.md`, the skills), where an ID like MD_0007 is an illustration, nor the
  templates, whose placeholder IDs are the point. I21 is the mirror of it
  pointed outward: it scans a listed consumer's own files, where an ID is a
  reliance rather than an illustration.
- HTML comments are stripped before any token scan, which is what makes a
  commented-out example in `bibliography.md` legal.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

from . import CheckError, ConfigError
