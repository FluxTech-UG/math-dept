def bibliography_path(root: Path, kind: str) -> Path:
    """The bibliography this repo checks against.

    There is one bibliography and it lives in the public repo, because citations
    are public even while the reading behind them is not. A private repo with no
    local copy therefore resolves the public sibling's, which is what makes the
    tag-to-extract sync (I11) meaningful across the pair.
    """
    local = Path(root) / "bibliography.md"
    if local.is_file() or kind == "public":
        return local
    sibling = config.public_root(root)
    if sibling is None:
        raise ConfigError(
            f"{root} has no bibliography.md and no public sibling to read one from. "
            "Set repos.yaml public_sibling, or MATHDEPT_PUBLIC."
        )
    return sibling / "bibliography.md"


def build_context(root: Path, run_counterexamples: bool, family: bool, lean: bool) -> Context:
    root = Path(root).resolve()
    _precheck_filenames(root)
    located = family_mod.locate(root)
    repo = located.repo_at(root)
    entries = repo.entries()
    kind = repo.kind
    bibliography = parse.parse_bibliography(bibliography_path(root, kind))
    ctx = Context(
        root=root,
        kind=kind,
        entries=entries,
        by_id={e.front.get("id"): e for e in entries},
        bibliography=bibliography,
        requests=repo.requests(),
        run_counterexamples=run_counterexamples,
        family=family,
        lean=lean,
    )
    if family:
        repos_yaml = root / "repos.yaml"
        if not repos_yaml.is_file():
            raise ConfigError(
                f"--family needs {repos_yaml}, which maps consumer names to paths. "
                "It lives in the private repo; run --family from a session there."
            )
        ctx.consumers = located.consumers
        ctx.sibling = located.sibling_of(root)
        # Eagerly, not lazily: the design's rule is that a repo listed in
        # repos.yaml and absent from disk FAILS. Resolving only the repos some
        # entry happens to name would let a stale path sit unnoticed until the
        # first entry that needs it, which is the wrong time to find out.
        for consumer in sorted(ctx.consumers):
            _consumer_path(ctx, consumer)
    if lean:
        cached = root / "audit" / "latest.json"
        if not cached.is_file():
            raise ConfigError(f"--lean needs {cached}; generate it with `make lean`")
        ctx.audit = audit_mod.read_cached_audit(root)
    return ctx


def run(root: Path | str | None = None,
        run_counterexamples: bool = False,
        family: bool = False,
        lean: bool = False) -> Context:
    """Run every invariant in order. Raises `CheckError` on the first violation."""
    resolved = config.find_repo_root(root) if root is None else Path(root).resolve()
    ctx = build_context(resolved, run_counterexamples, family, lean)
    for invariant in INVARIANTS:
        invariant(ctx)
    return ctx


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m mdept.check", description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=None, help="repo root (default: nearest ancestor with ledger/)")
    parser.add_argument("--run-counterexamples", action="store_true",
                        help="execute every counterexample artifact and require its witness to verify")
    parser.add_argument("--family", action="store_true",
                        help="resolve sibling and consumer repos through repos.yaml")
    parser.add_argument("--lean", action="store_true",
                        help="check formal pointers against the cached audit/latest.json")
    args = parser.parse_args(argv)
    try:
        ctx = run(args.root, args.run_counterexamples, args.family, args.lean)
    except (CheckError, ConfigError) as exc:
        print(f"FAIL {exc}", file=sys.stderr)
        return 1
    modes = [name for name, on in
             (("counterexamples", args.run_counterexamples), ("family", args.family), ("lean", args.lean)) if on]
    print(f"ok {len(ctx.entries)} entries, {len(INVARIANTS)} invariants"
          f"{', modes: ' + ', '.join(modes) if modes else ''} [{ctx.kind} repo]")
    for notice in ctx.notices:
        print(f"notice {notice}")
    return 0


