"""The ledger catalog: one line per entry, under a fixed token budget, for a reader who does not yet know the ID.

`ledger/CATALOG.md` is the first of three reading tiers: a catalog line, the
card `python -m mdept.query MD_0007` prints, the entry file. It is the one file
a session reads without knowing what it is looking for, so its size is capped:
`CATALOG_TOKEN_BUDGET` tokens, counted as `ceil(characters / CHARS_PER_TOKEN)`
(a stated approximation of a subword tokenizer on English and LaTeX source, not
a tokenizer run).

A catalog that fits is one file, its lines grouped under one `##` heading per
primary topic (an entry's first topic) in the llms.txt shape: H1, a blockquote
saying how to use it, then the lists. A catalog past the budget is split: one
`ledger/CATALOG-<topic>.md` per primary topic, and `CATALOG.md` becomes their
table of contents. A topic file past the budget is a failure that names it,
because its fix (a narrower first topic on some entries) is a judgment, not a
rendering choice.

The public repo's catalog covers its own entries. The private repo's covers both
ledgers, because every consumer is private and reads one catalog.
"""

from __future__ import annotations

import math

from . import CheckError
from . import schema, words

CATALOG_PATH = "ledger/CATALOG.md"
CATALOG_TOPIC_PATH = "ledger/CATALOG-{topic}.md"
#: The token budget of every catalog file.
CATALOG_TOKEN_BUDGET = 8000
#: The tokenizer the budget is measured with: characters per token.
CHARS_PER_TOKEN = 4
#: How much of a Statement one catalog line carries.
CATALOG_STATEMENT_WIDTH = 160

HEADER = "<!-- Generated by `python -m mdept.index`. Do not edit. Run: make regen -->"


def token_count(text: str) -> int:
    """The budget's measure of `text`: characters divided by `CHARS_PER_TOKEN`, rounded up."""
    return math.ceil(len(text) / CHARS_PER_TOKEN)


def primary_topic(entry) -> str:
    """The topic an entry is filed under in the catalog: its first."""
    return entry.front["topics"][0]


def line(entry) -> str:
    """One entry's catalog line: `- ID status: title | aka names | the Statement's opening`."""
    parts = [f"- {entry.id} {entry.status}: {entry.title}"]
    aka = entry.front.get("aka") or []
    if aka:
        parts.append("aka " + "; ".join(aka))
    if entry.front.get("merged_into"):
        parts.append(f"merged into {entry.front['merged_into']}")
    statement = words.display(entry.sections().get("Statement", ""))
    if statement:
        parts.append(words.cut(statement, CATALOG_STATEMENT_WIDTH))
    return " | ".join(parts)


def _citation_rule() -> str:
    """The citing rule, read off `schema.CITATION_WORDS` so it has one home."""
    clauses = []
    by_words: dict[tuple, list[str]] = {}
    for status, required in schema.CITATION_WORDS.items():
        by_words.setdefault(required, []).append(status)
    for required, statuses in by_words.items():
        shown = ", ".join(f"`{w}`" for w in required)
        clauses.append(f"a line citing a {' or '.join(statuses)} entry carries "
                       + (shown if len(required) == 1 else f"one of {shown}"))
    rule = "; ".join(clauses)
    return f"Cite an entry by its ID. {rule[0].upper()}{rule[1:]}."


def _preamble(scope: str, split: bool) -> list[str]:
    lines = [
        f"> Every entry of {scope}, one line each: `ID status: title | aka informal names | "
        "the Statement's opening`. Refuted and merged entries stay listed: they are what stops "
        "a statement being stipulated twice.",
        "> `python -m mdept.query \"<your own words>\"` ranks entries against a question; "
        "`python -m mdept.query MD_0007` prints one entry's card (statement, hypotheses, Lean "
        "name, links, citations).",
        f"> {_citation_rule()}",
    ]
    if split:
        lines.append(
            "> This catalog passed its budget and is split by primary topic (an entry's first "
            "topic): below are the topics and their entries' titles; the full lines are in each "
            "topic's file."
        )
    return lines


def _by_topic(entries) -> dict[str, list]:
    topics: dict[str, list] = {}
    for entry in sorted(entries, key=lambda e: e.id):
        topics.setdefault(primary_topic(entry), []).append(entry)
    return dict(sorted(topics.items()))


def _single(entries, scope: str) -> str:
    lines = ["# Ledger catalog", HEADER, ""] + _preamble(scope, split=False)
    for topic, members in _by_topic(entries).items():
        lines += ["", f"## {topic}", ""] + [line(entry) for entry in members]
    return "\n".join(lines) + "\n"


def _topic_file(topic: str, members) -> str:
    lines = [
        f"# Ledger catalog: {topic}",
        HEADER,
        "",
        f"> The entries whose first topic is `{topic}`, one line each. The table of contents "
        "and how to search are in `CATALOG.md`.",
        "",
    ]
    lines += [line(entry) for entry in members]
    return "\n".join(lines) + "\n"


def _contents(topics: dict[str, list], scope: str, titles: bool) -> str:
    """The table of contents: per topic its file, and with `titles` every entry's ID, status and title."""
    lines = ["# Ledger catalog", HEADER, ""] + _preamble(scope, split=True)
    for topic, members in topics.items():
        others = sorted({t for e in members for t in e.front["topics"] if t != topic})
        noun = "entry" if len(members) == 1 else "entries"
        lines += ["", f"## [{topic}](CATALOG-{topic}.md)", "",
                  f"{len(members)} {noun}" + (f"; also {', '.join(others)}" if others else "") + "."]
        if titles:
            lines += [""] + [f"- {entry.id} {entry.status}: {entry.title}" for entry in members]
    return "\n".join(lines) + "\n"


def render(entries, scope: str, budget: int = CATALOG_TOKEN_BUDGET) -> dict[str, str]:
    """The catalog files as {repo-relative path: content}: one file, or a contents file and one per topic.

    The contents file lists every entry's ID, status and title under its topic
    while that fits the budget, and only the topics once it does not.
    """
    single = _single(entries, scope)
    if token_count(single) <= budget:
        return {CATALOG_PATH: single}
    topics = _by_topic(entries)
    contents = _contents(topics, scope, titles=True)
    if token_count(contents) > budget:
        contents = _contents(topics, scope, titles=False)
    files = {CATALOG_PATH: contents}
    for topic, members in topics.items():
        files[CATALOG_TOPIC_PATH.format(topic=topic)] = _topic_file(topic, members)
    over = [f"{rel} ({token_count(text)} tokens)" for rel, text in files.items() if token_count(text) > budget]
    if over:
        raise CheckError(
            f"I16 generated: {', '.join(over)}: field '<content>': past the catalog budget of {budget} "
            f"tokens (characters / {CHARS_PER_TOKEN}); give some of the entries filed there a narrower "
            "first topic"
        )
    return files
