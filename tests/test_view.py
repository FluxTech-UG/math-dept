"""`python -m mdept.view`: the consumer's generated view, and its drift guard.

The guard is the point of the command. A view that is written once and then
quietly ages is worse than no view, because a reader trusts it; `--check` is
what makes it a guard, so the cases here are mostly about what must make it
fail.
"""

import shutil
from pathlib import Path

import pytest

from mdept import CheckError, ConfigError
from mdept import family as family_mod
from mdept import view

FIXTURES = Path(__file__).resolve().parent / "fixtures"
BASES = ("good_public", "good_private")


def stage(tmp_path: Path) -> Path:
    for base in BASES:
        shutil.copytree(FIXTURES / base, tmp_path / base,
                        ignore=shutil.ignore_patterns("__pycache__"))
    return tmp_path


@pytest.fixture
def private(tmp_path):
    return stage(tmp_path) / "good_private"


def run(root: Path, *args) -> int:
    return view.main(["--consumer", "ToyRepo", "--root", str(root), *args])


# --- write, then check -----------------------------------------------------


def test_write_then_check_is_green(private, capsys):
    assert run(private, "--write") == 0
    assert run(private, "--check") == 0
    assert "is fresh" in capsys.readouterr().out


def test_check_fails_before_the_view_has_ever_been_written(private, capsys):
    """Nothing requires the view to exist: `--check` says so and fails.

    The file is generated on demand, so a consumer that has not run `--write`
    yet is in a legal state, and no other command may depend on the path being
    there.
    """
    assert not (private / "consumers/ToyRepo/docs/MATH.md").exists()
    assert run(private, "--check") == 1
    assert "does not exist" in capsys.readouterr().err


def test_a_status_change_makes_check_fail(private, capsys):
    assert run(private, "--write") == 0
    entry = private / "ledger/MD_0006.md"
    entry.write_text(entry.read_text(encoding="utf-8").replace("status: open", "status: refuted"),
                     encoding="utf-8")
    assert run(private, "--check") == 1
    assert "drifted from the ledger" in capsys.readouterr().err


def test_the_write_is_deterministic(private):
    assert run(private, "--write") == 0
    first = (private / "consumers/ToyRepo/docs/MATH.md").read_text(encoding="utf-8")
    assert run(private, "--write") == 0
    assert (private / "consumers/ToyRepo/docs/MATH.md").read_text(encoding="utf-8") == first


def test_out_writes_a_preview_somewhere_else(private, tmp_path):
    preview = tmp_path / "preview" / "MATH.md"
    assert run(private, "--write", "--out", str(preview)) == 0
    assert preview.is_file()
    assert not (private / "consumers/ToyRepo/docs/MATH.md").exists()
    assert "--consumer ToyRepo --write" in preview.read_text(encoding="utf-8"), (
        "the header names the real command, not the preview path"
    )


# --- what the file says ----------------------------------------------------


def test_the_opening_lines_declare_the_file_generated(private):
    family = family_mod.load_family(private)
    text, _path, _payload = view.generate(family, "ToyRepo")
    head = "\n".join(text.splitlines()[:8]).lower()
    assert "generated by" in head, (
        "a consumer's own generated-file scanner reads the first 8 lines for this"
    )
    assert view.HEADER_NOTE in head


def test_the_view_reports_raised_cited_and_request_tokens(private):
    family = family_mod.load_family(private)
    _text, path, payload = view.generate(family, "ToyRepo")
    assert path == private / "consumers/ToyRepo/docs/MATH.md"
    assert [record["id"] for record in payload["raised"]] == ["MD_0005", "MD_0006", "MD_0007"]
    assert [(c["id"], c["path"], c["line"]) for c in payload["cited"]] == [
        ("MD_0005", "docs/toy.md", 5),
        ("MD_0006", "docs/toy.md", 6),
        ("MD_0006", "research/toy notes.md", 4),
        ("MD_0005", "src/toy.py", 3),
    ]
    assert payload["cited"][2]["locator"] == "§2", (
        "a quoted cited_by path keeps its locator, which is the reason for quoting"
    )


