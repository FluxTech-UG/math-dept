# --- what counts as generated, and what counts as readable -----------------


def test_the_generated_marker_has_to_open_a_line(private):
    """Prose about something "generated by hand" does not exempt a file.

    The skip is a real exemption from I21, so it has to be a declaration rather
    than a coincidence of wording. Anything a generator actually writes at the
    top of a file still counts.
    """
    consumer = family_mod.load_family(private).consumer("ToyRepo")
    path = private / "consumers/ToyRepo/docs/probe.md"
    for text, generated in [
        ("<!-- Generated by `tool` -->\n", True),
        ("> Generated by `repo-outline`\n", True),
        ("<!-- role: generated | status: current 2026-09-17 -->\n", True),
        ("**Generated by `scripts/gen.py`**\n", True),
        ("# Notes\n\nThe table below was generated by hand, so it stays.\n", False),
        ("# Notes\n\nA line about role: generated files in general.\n", False),
    ]:
        path.write_text(text, encoding="utf-8")
        assert consumer.is_generated(path) is generated, text


def test_a_file_with_no_prose_to_scan_is_skipped_and_never_crashes(private):
    """None from `text` means "nothing to scan here", for two definite reasons."""
    consumer = family_mod.load_family(private).consumer("ToyRepo")
    toy = private / "consumers/ToyRepo"
    (toy / "docs/dangling.md").symlink_to(toy / "docs/nowhere.md")
    (toy / "docs/binary.bin").write_bytes(b"\x00\xff\xfe MD_0005 \x00")
    assert consumer.text(toy / "docs/dangling.md") is None
    assert consumer.text(toy / "docs/binary.bin") is None
    assert consumer.is_generated(toy / "docs/dangling.md") is False


def test_an_unreadable_regular_file_fails_instead_of_reading_as_empty(private):
    """A permission problem reported as "no citations here" is the worst answer.

    The file is a regular file in a listed consumer, so it is a citation surface;
    being unable to read it is a finding, not a licence to skip it.
    """
    consumer = family_mod.load_family(private).consumer("ToyRepo")
    locked = private / "consumers/ToyRepo/docs/locked.md"
    locked.write_text("It cites MD_0005 (open).\n", encoding="utf-8")
    locked.chmod(0o000)
    try:
        with pytest.raises(CheckError, match="cannot be read"):
            consumer.text(locked)
    finally:
        locked.chmod(0o644)


