# --- what the scan skips ---------------------------------------------------


def test_a_generated_file_and_an_ignored_tree_are_not_scanned(private):
    """Both fixture files carry an `MDR:` token that must not reach the view.

    They are the same two files I21 skips, for the same two reasons: a generated
    file mirrors an editable one, and an ignored tree is not this repo's surface.
    """
    toy = private / "consumers/ToyRepo"
    (toy / "docs/generated_notes.md").write_text(
        "# Toy generated notes\n<!-- Generated by the toy pipeline. Do not edit. -->\n\n"
        "A mirror naming MDR:2026-09-01-toy#C1 (pending).\n",
        encoding="utf-8",
    )
    (toy / "vendor/third_party.md").write_text(
        "# Vendored\n\nIt names MDR:2026-09-01-toy#C1 (pending) and is not our surface.\n",
        encoding="utf-8",
    )
    (toy / "docs/own.md").write_text(
        "# Our own note\n\nIt cites MDR:2026-09-01-toy#C1 (pending).\n", encoding="utf-8"
    )
    family = family_mod.load_family(private)
    _text, _path, payload = view.generate(family, "ToyRepo")
    assert [record["found_at"] for record in payload["requests"]] == [["docs/own.md:3"]]
    assert payload["requests"][0]["candidates"] == {"C1": "pending"}


def test_a_nested_checkout_is_another_repo_and_is_not_scanned(private):
    """An agent worktree under `.claude/` carries a copy of every citation.

    Counting it would make the same check pass or fail depending on whether
    someone is working in a worktree at that moment, which is the one thing a
    guard may not do.
    """
    tooling = private / "consumers/ToyRepo/.claude"
    checkout = tooling / "worktrees/agent-1"
    (checkout / "docs").mkdir(parents=True)
    (checkout / ".git").write_text("gitdir: elsewhere\n", encoding="utf-8")
    (checkout / "docs/own.md").write_text(
        "A copy citing MDR:2026-09-01-toy#C1 (pending).\n", encoding="utf-8"
    )
    (tooling / "settings.json").write_text("{}\n", encoding="utf-8")
    consumer = family_mod.load_family(private).consumer("ToyRepo")
    scanned = {consumer.rel(path) for path in consumer.files()}
    assert ".claude/worktrees/agent-1/docs/own.md" not in scanned
    assert ".claude/settings.json" in scanned, (
        "the rule is the nested checkout, not a blanket skip of a tooling directory"
    )


